//! Real TSF edit sessions against an already focused qualification editor.
use std::cell::RefCell;
use std::rc::Rc;
use windows::Win32::Foundation::{E_FAIL, E_INVALIDARG, HWND, RECT};
use windows::Win32::System::Com::{CLSCTX_INPROC_SERVER, CoCreateInstance};
use windows::Win32::System::Threading::GetCurrentThreadId;
use windows::Win32::UI::TextServices::{
    CLSID_TF_ThreadMgr, ITfContext, ITfEditSession, ITfEditSession_Impl, ITfThreadMgr,
    TF_ANCHOR_END, TF_E_SYNCHRONOUS, TF_ES_ASYNCDONTCARE, TF_ES_READWRITE, TF_ES_SYNC,
};
use windows::Win32::UI::WindowsAndMessaging::GetWindowThreadProcessId;
use windows_core::{BOOL, implement};

/// Text and screen geometry read inside a real TSF read/write grant.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeTextGrant {
    /// Full document before the edit, bounded to 4096 UTF-16 code units.
    pub before: String,
    /// Full document read back under the same grant after replacement.
    pub after: String,
    /// Original document's screen rectangle: left, top, right, bottom.
    pub bounds: [i32; 4],
    /// Whether the original text rectangle was clipped by the native view.
    pub clipped: bool,
    /// Thread which received the actual edit-session callback.
    pub owner: std::thread::ThreadId,
}

/// Native edit-session admission failures distinguished from deferred work.
#[derive(Debug, thiserror::Error)]
pub enum NativeTextGrantError {
    /// TSF specifically refused an immediate read/write grant.
    #[error("TSF synchronous grant unavailable")]
    SynchronousUnavailable,
    /// Setup or another COM operation failed, not a commit-gate refusal.
    #[error("native text grant failed: {0}")]
    Native(String),
}

#[expect(
    clippy::ref_as_ptr,
    clippy::inline_always,
    raw_borrows_via_references,
    reason = "code generated by windows-core's #[implement]"
)]
mod session {
    use super::{
        BOOL, E_FAIL, E_INVALIDARG, ITfContext, ITfEditSession, ITfEditSession_Impl,
        NativeTextGrant, RECT, Rc, RefCell, TF_ANCHOR_END, implement,
    };

    #[implement(ITfEditSession, Agile = false)]
    pub(super) struct Replace {
        pub context: ITfContext,
        pub text: Vec<u16>,
        pub result: Rc<RefCell<Option<Result<NativeTextGrant, String>>>>,
    }

    impl ITfEditSession_Impl for Replace_Impl {
        fn DoEditSession(&self, cookie: u32) -> windows_core::Result<()> {
            crate::owner::panic_boundary::os_entry(
                "qualification::DoEditSession",
                (),
                crate::owner::panic_boundary::AfterPanic::Answer(|()| {
                    Err(windows_core::Error::from_hresult(E_FAIL))
                }),
                || {
                    let result = self.replace(cookie);
                    let status = result
                        .as_ref()
                        .map(|_| ())
                        .map_err(|error| windows_core::Error::from_hresult(error.code()));
                    *self.result.borrow_mut() = Some(result.map_err(|error| error.to_string()));
                    status
                },
            )
        }
    }
    impl Replace_Impl {
        fn replace(&self, cookie: u32) -> windows_core::Result<NativeTextGrant> {
            // SAFETY: TSF supplied this context's read/write cookie on its
            // STA. All interfaces and buffers remain local to the callback.
            unsafe {
                let range = self.context.GetStart(cookie)?;
                let end = self.context.GetEnd(cookie)?;
                range.ShiftEndToRange(cookie, &end, TF_ANCHOR_END)?;
                let read = || -> windows_core::Result<String> {
                    let mut buffer = [0_u16; 4097];
                    let mut length = 0;
                    range.GetText(cookie, 0, &mut buffer, &raw mut length)?;
                    if length > 4096 {
                        return Err(windows_core::Error::from_hresult(E_INVALIDARG));
                    }
                    String::from_utf16(&buffer[..length as usize])
                        .map_err(|_| windows_core::Error::from_hresult(E_FAIL))
                };
                let before = read()?;
                let mut bounds = RECT::default();
                let mut clipped = BOOL::default();
                self.context.GetActiveView()?.GetTextExt(
                    cookie,
                    &range,
                    &raw mut bounds,
                    &raw mut clipped,
                )?;
                range.SetText(cookie, 0, &self.text)?;
                let after = read()?;
                let observation = NativeTextGrant {
                    before,
                    after,
                    bounds: [bounds.left, bounds.top, bounds.right, bounds.bottom],
                    clipped: clipped.as_bool(),
                    owner: std::thread::current().id(),
                };
                Ok(observation)
            }
        }
    }
}

struct Activation(ITfThreadMgr);
impl Drop for Activation {
    fn drop(&mut self) {
        // SAFETY: balances this helper's successful activation on its STA,
        // after the owned session and context interfaces have been released.
        let _ = unsafe { self.0.Deactivate() };
    }
}

/// Owner-local receipt retaining a real native edit session until observation.
pub struct NativeTextGrantRequest {
    result: Rc<RefCell<Option<Result<NativeTextGrant, String>>>>,
    _session: ITfEditSession,
    _activation: Activation,
}
impl std::fmt::Debug for NativeTextGrantRequest {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("NativeTextGrantRequest")
            .finish_non_exhaustive()
    }
}
impl NativeTextGrantRequest {
    /// Consume the actual callback outcome; `None` means no grant has arrived.
    pub fn take_result(&self) -> Option<Result<NativeTextGrant, String>> {
        self.result.borrow_mut().take()
    }
}

/// Request an edit through the owner's real TSF context. Call on
/// the window's STA after native keyboard focus settled. A synchronous request
/// during a frame must be refused; an asynchronous request may wait for Idle.
/// The HWND and current context must agree before any edit is requested.
/// This is an edit-session client, not an IME composition/candidate simulation.
pub fn request_focused_text_through_tsf(
    window: flui_platform::WindowId,
    text: &str,
    timing: flui_platform::text_store::LockTiming,
) -> Result<NativeTextGrantRequest, NativeTextGrantError> {
    fn execute(
        window: flui_platform::WindowId,
        text: &str,
        timing: flui_platform::text_store::LockTiming,
    ) -> windows_core::Result<NativeTextGrantRequest> {
        let hwnd = HWND(window.0 as *mut _);
        // SAFETY: scalar queries only; no native owner state is dereferenced.
        if unsafe { GetWindowThreadProcessId(hwnd, None) != GetCurrentThreadId() }
            || text.encode_utf16().count() > 4096
        {
            return Err(windows_core::Error::from_hresult(E_INVALIDARG));
        }
        // SAFETY: the checked window owner has initialized its COM apartment;
        // this manager and every derived interface remain on that same thread.
        unsafe {
            let manager: ITfThreadMgr =
                CoCreateInstance(&CLSID_TF_ThreadMgr, None, CLSCTX_INPROC_SERVER)?;
            let client = manager.Activate()?;
            let activation = Activation(manager);
            let context = activation.0.GetFocus()?.GetTop()?;
            if context.GetActiveView()?.GetWnd()? != hwnd {
                return Err(windows_core::Error::from_hresult(E_INVALIDARG));
            }
            let observed = Rc::new(RefCell::new(None));
            let session: ITfEditSession = session::Replace {
                context: context.clone(),
                text: text.encode_utf16().collect::<Vec<u16>>(),
                result: Rc::clone(&observed),
            }
            .into();
            let flags = match timing {
                flui_platform::text_store::LockTiming::Sync => TF_ES_SYNC,
                flui_platform::text_store::LockTiming::Async => TF_ES_ASYNCDONTCARE,
            };
            context
                .RequestEditSession(client, &session, flags | TF_ES_READWRITE)?
                .ok()?;
            Ok(NativeTextGrantRequest {
                result: observed,
                _session: session,
                _activation: activation,
            })
        }
    }
    execute(window, text, timing).map_err(|error| {
        if error.code() == TF_E_SYNCHRONOUS {
            NativeTextGrantError::SynchronousUnavailable
        } else {
            NativeTextGrantError::Native(error.to_string())
        }
    })
}
