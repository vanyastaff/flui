//! What a field is for, as TSF's input scope: the `GUID_PROP_INPUTSCOPE`
//! attribute an input method reads through `ITextStoreACP`'s attribute
//! methods, so a protected field gets the password layout and no plain
//! reading in the candidate window, and an email, URL, phone or number field
//! the keyboard its purpose asks for.

use flui_platform::text_store::{TextInputPurpose, TextStoreStatus};
use windows::Win32::{
    Foundation::{E_NOTIMPL, E_UNEXPECTED},
    System::{Com::CoTaskMemAlloc, Variant::VARIANT},
    UI::TextServices::{
        GUID_PROP_INPUTSCOPE, IS_DIGITS, IS_EMAIL_SMTPEMAILADDRESS, IS_PASSWORD, IS_SEARCH,
        IS_TELEPHONE_FULLTELEPHONENUMBER, IS_URL, ITfInputScope, ITfInputScope_Impl, InputScope,
        TS_ATTR_FIND_WANT_VALUE,
    },
};
use windows_core::{BSTR, GUID};

use crate::owner::panic_boundary::{AfterPanic, os_entry};

/// The input scope a field of `status` asks for, or `None` for plain text
/// (the default, which an input method assumes without being told).
pub(super) fn scope_for(status: TextStoreStatus) -> Option<InputScope> {
    if status.protected {
        return Some(IS_PASSWORD);
    }
    match status.purpose {
        TextInputPurpose::Email => Some(IS_EMAIL_SMTPEMAILADDRESS),
        TextInputPurpose::Url => Some(IS_URL),
        TextInputPurpose::Phone => Some(IS_TELEPHONE_FULLTELEPHONENUMBER),
        TextInputPurpose::Number => Some(IS_DIGITS),
        TextInputPurpose::Search => Some(IS_SEARCH),
        // `Text`, and a purpose added later that has no scope yet.
        _ => None,
    }
}

/// Whether an attribute filter of `count` GUIDs at `filter` asks for the
/// input scope: an empty filter asks for every attribute.
///
/// # Safety
///
/// `filter` must point at `count` readable GUIDs, or `count` must be 0.
pub(super) unsafe fn filter_wants_scope(count: u32, filter: *const GUID) -> bool {
    if count == 0 || filter.is_null() {
        return true;
    }
    // SAFETY: the caller guarantees `count` readable GUIDs at `filter`.
    let filter = unsafe { std::slice::from_raw_parts(filter, count as usize) };
    filter.contains(&GUID_PROP_INPUTSCOPE)
}

/// How TSF asked for the input scope: only whether the document has one, or
/// for its value too (`TS_ATTR_FIND_WANT_VALUE`). A probe is answered with an
/// empty value, as `ITextStoreACP::RequestSupportedAttrs` requires.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum ScopeRequest {
    Probe,
    Value,
}

impl ScopeRequest {
    /// The request a `RequestAttrsAtPosition` call with a filter of `count`
    /// GUIDs at `filter` makes, if it names the input scope.
    ///
    /// # Safety
    ///
    /// As for [`filter_wants_scope`].
    pub(super) unsafe fn at_position(count: u32, filter: *const GUID) -> Option<Self> {
        // A request at a position has no probe form (its flags are reserved),
        // so it always wants the value.
        // SAFETY: the caller's guarantee.
        unsafe { Self::from_request(TS_ATTR_FIND_WANT_VALUE, count, filter) }
    }

    /// The request `flags` and a filter of `count` GUIDs at `filter` make, if
    /// it names the input scope.
    ///
    /// # Safety
    ///
    /// As for [`filter_wants_scope`].
    pub(super) unsafe fn from_request(flags: u32, count: u32, filter: *const GUID) -> Option<Self> {
        // SAFETY: the caller's guarantee.
        if !unsafe { filter_wants_scope(count, filter) } {
            return None;
        }
        Some(if flags & TS_ATTR_FIND_WANT_VALUE != 0 {
            Self::Value
        } else {
            Self::Probe
        })
    }
}

/// The attribute TSF reads for the scope `scope`: the attribute id and, for a
/// request that wants the value, an `ITfInputScope` holding that one scope.
pub(super) fn scope_attribute(
    scope: InputScope,
    request: ScopeRequest,
) -> windows::Win32::UI::TextServices::TS_ATTRVAL {
    let value = match request {
        ScopeRequest::Probe => VARIANT::default(),
        ScopeRequest::Value => {
            let object: ITfInputScope = SingleScope { scope }.into();
            let unknown: windows_core::IUnknown = windows_core::Interface::cast(&object)
                .expect("BUG: every COM object answers IUnknown");
            unknown.into()
        }
    };
    windows::Win32::UI::TextServices::TS_ATTRVAL {
        idAttr: GUID_PROP_INPUTSCOPE,
        dwOverlapId: 0,
        varValue: value,
    }
}

/// The `#[implement]` expansion, in a module of its own so the lints its
/// generated code trips are expected here and nowhere else.
#[expect(
    clippy::ref_as_ptr,
    clippy::inline_always,
    raw_borrows_via_references,
    reason = "code generated by windows-core's #[implement]"
)]
mod com_object {
    use windows::Win32::UI::TextServices::{ITfInputScope, InputScope};
    use windows_core::implement;

    /// An `ITfInputScope` of one scope.
    #[implement(ITfInputScope)]
    pub(super) struct SingleScope {
        pub(super) scope: InputScope,
    }
}
use com_object::{SingleScope, SingleScope_Impl};

/// The boundary every vtable method of [`SingleScope`] crosses: a panic
/// answers `E_UNEXPECTED`.
fn com_method<R>(body: impl FnOnce() -> windows_core::Result<R>) -> windows_core::Result<R> {
    os_entry(
        "the input scope",
        (),
        AfterPanic::Answer(|()| Err(E_UNEXPECTED.into())),
        body,
    )
}

impl ITfInputScope_Impl for SingleScope_Impl {
    fn GetInputScopes(
        &self,
        pprginputscopes: *mut *mut InputScope,
        pccount: *mut u32,
    ) -> windows_core::Result<()> {
        com_method(|| {
            if pprginputscopes.is_null() || pccount.is_null() {
                return Err(windows::Win32::Foundation::E_POINTER.into());
            }
            // SAFETY: TSF frees the array with `CoTaskMemFree`, so it is
            // allocated with `CoTaskMemAlloc`; the allocation is checked before
            // the write and both out-pointers were checked above.
            unsafe {
                let array = CoTaskMemAlloc(size_of::<InputScope>()).cast::<InputScope>();
                if array.is_null() {
                    return Err(windows::Win32::Foundation::E_OUTOFMEMORY.into());
                }
                array.write(self.scope);
                pprginputscopes.write(array);
                pccount.write(1);
            }
            Ok(())
        })
    }

    fn GetPhrase(
        &self,
        _ppbstrphrases: *mut *mut BSTR,
        _pccount: *mut u32,
    ) -> windows_core::Result<()> {
        com_method(|| Err(E_NOTIMPL.into()))
    }

    fn GetRegularExpression(&self) -> windows_core::Result<BSTR> {
        com_method(|| Err(E_NOTIMPL.into()))
    }

    fn GetSRGS(&self) -> windows_core::Result<BSTR> {
        com_method(|| Err(E_NOTIMPL.into()))
    }

    fn GetXML(&self) -> windows_core::Result<BSTR> {
        com_method(|| Err(E_NOTIMPL.into()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_field_gets_the_scope_its_status_asks_for() {
        let plain = TextStoreStatus::EDITABLE_SINGLE_LINE;
        let cases = [
            (plain, None),
            (plain.with_protected(true), Some(IS_PASSWORD)),
            // Protection wins over what the field is for: the reading of a
            // hidden email must not show in the candidate window.
            (
                plain
                    .with_protected(true)
                    .with_purpose(TextInputPurpose::Email),
                Some(IS_PASSWORD),
            ),
            (
                plain.with_purpose(TextInputPurpose::Email),
                Some(IS_EMAIL_SMTPEMAILADDRESS),
            ),
            (plain.with_purpose(TextInputPurpose::Url), Some(IS_URL)),
            (
                plain.with_purpose(TextInputPurpose::Phone),
                Some(IS_TELEPHONE_FULLTELEPHONENUMBER),
            ),
            (
                plain.with_purpose(TextInputPurpose::Number),
                Some(IS_DIGITS),
            ),
            (
                plain.with_purpose(TextInputPurpose::Search),
                Some(IS_SEARCH),
            ),
        ];
        for (status, expected) in cases {
            assert_eq!(scope_for(status), expected, "{status:?}");
        }
    }

    #[test]
    fn a_request_wants_the_value_only_when_it_says_so() {
        let other = GUID::from_u128(1);
        // SAFETY: each filter points at as many GUIDs as its count says.
        unsafe {
            let ask = |flags, count, filter| ScopeRequest::from_request(flags, count, filter);
            assert_eq!(ask(0, 1, &GUID_PROP_INPUTSCOPE), Some(ScopeRequest::Probe));
            assert_eq!(
                ask(TS_ATTR_FIND_WANT_VALUE, 1, &GUID_PROP_INPUTSCOPE),
                Some(ScopeRequest::Value)
            );
            assert_eq!(ask(TS_ATTR_FIND_WANT_VALUE, 1, &raw const other), None);
            // A request at a position has no probe form.
            assert_eq!(
                ScopeRequest::at_position(1, &GUID_PROP_INPUTSCOPE),
                Some(ScopeRequest::Value)
            );
        }
    }

    #[test]
    fn a_filter_asks_for_the_scope_when_empty_or_naming_it() {
        let other = GUID::from_u128(1);
        // SAFETY: each filter points at as many GUIDs as its count says.
        unsafe {
            assert!(filter_wants_scope(0, std::ptr::null()));
            assert!(filter_wants_scope(1, &GUID_PROP_INPUTSCOPE));
            assert!(!filter_wants_scope(1, &raw const other));
            let both = [other, GUID_PROP_INPUTSCOPE];
            assert!(filter_wants_scope(2, both.as_ptr()));
        }
    }
}
