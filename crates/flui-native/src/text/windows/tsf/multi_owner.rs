#[expect(
    clippy::ref_as_ptr,
    clippy::inline_always,
    raw_borrows_via_references,
    reason = "code generated by windows-core's #[implement]"
)]
mod edit_session {
    use std::cell::Cell;
    use std::rc::Rc;
    use windows::Win32::UI::TextServices::{
        ITfContext, ITfEditSession, ITfEditSession_Impl, TF_ANCHOR_END,
    };
    use windows_core::implement;

    #[implement(ITfEditSession)]
    pub(super) struct Replace {
        pub(super) context: ITfContext,
        pub(super) text: Vec<u16>,
        pub(super) called_on: Rc<Cell<Option<std::thread::ThreadId>>>,
    }

    impl ITfEditSession_Impl for Replace_Impl {
        fn DoEditSession(&self, cookie: u32) -> windows_core::Result<()> {
            self.called_on.set(Some(std::thread::current().id()));
            // SAFETY: this call owns TSF's read/write cookie on the context's
            // STA. All interfaces and the UTF-16 buffer stay on this thread.
            unsafe {
                let range = self.context.GetStart(cookie)?;
                let end = self.context.GetEnd(cookie)?;
                range.ShiftEndToRange(cookie, &end, TF_ANCHOR_END)?;
                range.SetText(cookie, 0, &self.text)
            }
        }
    }
}

fn replace_through_tsf(services: &TextServices, text: &str, granted: bool) {
    let context = match &*services.serving.borrow() {
        Serving::Field(document) => document.context.clone(),
        Serving::Nothing | Serving::Shutdown => panic!("focused field has a TSF context"),
    };
    let called_on = Rc::new(Cell::new(None));
    let session: ITfEditSession = edit_session::Replace {
        context: context.clone(),
        text: text.encode_utf16().collect::<Vec<u16>>(),
        called_on: Rc::clone(&called_on),
    }
    .into();
    // SAFETY: the session, context and client all belong to this STA. TSF
    // synchronously enters the real ITextStoreACP grant for this context.
    let result = unsafe {
        context.RequestEditSession(services.client_id, &session, TF_ES_SYNC | TF_ES_READWRITE)
    };
    if !granted {
        assert!(
            result.is_err() || result.is_ok_and(windows_core::HRESULT::is_err),
            "a shut commit gate refuses a synchronous grant"
        );
        assert_eq!(called_on.get(), None);
        return;
    }
    assert_eq!(
        result.map(|hr| hr.0),
        Ok(0),
        "TSF grants a real synchronous edit"
    );
    assert_eq!(called_on.get(), Some(thread::current().id()));
}

enum Command {
    Edit(String),
    Hold(Receiver<()>),
    Input { prevent: bool },
    WindowMode,
    Stop,
}

#[derive(Debug)]
enum Receipt {
    Ready {
        thread: thread::ThreadId,
        hwnd: usize,
        client: u32,
    },
    Held,
    Released,
    Edited(String),
    Input,
    Mode(WindowMode),
    Retired,
}

fn run_owner(label: &'static str, commands: Receiver<Command>, receipts: SyncSender<Receipt>) {
    assert!(!thread_in_apartment());
    let platform = crate::WindowsPlatform::try_new().expect("native platform on fresh thread");
    assert!(thread_in_apartment());
    let log = AppLog::new();
    let weak_log = Rc::downgrade(&log);
    let remaining = Rc::new(Cell::new(None));
    let retired_hwnd = Rc::clone(&remaining);
    let report = receipts.clone();
    log.bootstrap(move |owner| {
        let handler = RecordingWindowHandler::new();
        let prevent = Rc::new(Cell::new(false));
        let input_count = Rc::new(Cell::new(0));
        let input_policy = Rc::clone(&prevent);
        let counted = Rc::clone(&input_count);
        handler.react_to_input(move |input| {
            if matches!(input, flui_platform::PlatformInput::Keyboard(_)) {
                counted.set(counted.get() + 1);
            }
            DispatchEventResult::resolved(true, input_policy.get())
        });
        let window = owner
            .open_window(
                WindowOptions::default()
                    .with_title("FLUI two-owner TSF qualification")
                    .with_visible(false),
                handler,
            )
            .expect("native window")
            .try_ready()
            .expect("bootstrap opens synchronously");
        let hwnd = window
            .as_any()
            .downcast_ref::<crate::window::windows::WindowsWindow>()
            .expect("Win32 window")
            .hwnd();
        // SAFETY: querying a live HWND created by this thread; no out pointer.
        assert_eq!(unsafe { GetWindowThreadProcessId(hwnd, None) }, unsafe {
            windows::Win32::System::Threading::GetCurrentThreadId()
        });
        retired_hwnd.set(Some(hwnd));
        let services = crate::text::windows::testing::services_of(hwnd).expect("window TSF");
        let store = InMemoryTextStore::new("initial");
        let gate = CommitGate::new();
        store.set_commit_gate(gate.clone());
        services.focus_store(Some(Rc::clone(&store) as Rc<dyn TextStore>));
        // A hidden window has no keyboard focus. The field still owns its
        // TSF document; requesting an edit below verifies its actual grant.
        assert!(matches!(*services.serving.borrow(), Serving::Field(_)));
        let root = accesskit::NodeId(1);
        let mut node = accesskit::Node::new(accesskit::Role::Window);
        node.set_label(label);
        window
            .accessibility()
            .expect("UIA bridge")
            .publish(accesskit::TreeUpdate {
                nodes: vec![(root, node)],
                tree: Some(accesskit::TreeInfo::new(root)),
                tree_id: accesskit::TreeId::ROOT,
                focus: root,
            });
        report
            .send(Receipt::Ready {
                thread: thread::current().id(),
                hwnd: hwnd.0 as usize,
                client: services.client_id,
            })
            .expect("ready receipt");
        let deadline = web_time::Instant::now() + Duration::from_secs(30);
        let log = weak_log.upgrade().expect("run holds handler");
        log.answer_deadline_with(|| Some(web_time::Instant::now() + Duration::from_millis(5)));
        log.react(move |call, owner| {
            if call != AppCall::WakeDeadline {
                return;
            }
            assert!(thread_in_apartment());
            let command = commands.try_recv();
            match command {
                Ok(Command::Edit(text)) => {
                    let before = store.text();
                    gate.set_open(false);
                    replace_through_tsf(&services, "must not be committed", false);
                    assert_eq!(store.text(), before);
                    gate.set_open(true);
                    replace_through_tsf(&services, &text, true);
                    assert_eq!(store.text(), text);
                    report
                        .send(Receipt::Edited(store.text()))
                        .expect("edit receipt");
                }
                Ok(Command::Input { prevent: blocked }) => {
                    prevent.set(blocked);
                    let before = input_count.get();
                    // SAFETY: plain F11 key messages to this thread's live HWND.
                    // No system-wide input injection and no foreground changes.
                    unsafe {
                        SendMessageW(
                            hwnd,
                            WM_KEYDOWN,
                            Some(WPARAM(0x7a)),
                            Some(LPARAM(0x0057_0001)),
                        );
                        SendMessageW(
                            hwnd,
                            WM_KEYUP,
                            Some(WPARAM(0x7a)),
                            Some(LPARAM(0xc057_0001_u32 as i32 as isize)),
                        );
                    }
                    assert_eq!(input_count.get(), before + 2);
                    report.send(Receipt::Input).expect("input receipt");
                }
                Ok(Command::WindowMode) => {
                    report
                        .send(Receipt::Mode(window.state().mode))
                        .expect("mode receipt");
                }
                Ok(Command::Hold(release)) => {
                    report.send(Receipt::Held).expect("held receipt");
                    let _ = release.recv_timeout(Duration::from_secs(15));
                    report.send(Receipt::Released).expect("release receipt");
                }
                Ok(Command::Stop) | Err(TryRecvError::Disconnected) => {
                    services.focus_store(None);
                    window.close_now();
                    owner.quit();
                }
                Err(TryRecvError::Empty) => {
                    if web_time::Instant::now() >= deadline {
                        window.close_now();
                        owner.quit();
                    }
                }
            }
        });
        Ok(())
    });
    SHUTDOWN_IN_APARTMENT.set(None);
    Box::new(platform)
        .run(Rc::clone(&log) as Rc<dyn crate::AppHandler>)
        .expect("native message loop");
    // Release captured services/window on their owner after the loop; the
    // existing apartment lease must keep COM alive through their destruction.
    log.react(|_, _| {});
    drop(log);
    let hwnd = remaining.get().expect("window was created");
    // SAFETY: IsWindow accepts a stale numeric handle and does not dereference it.
    assert!(!unsafe { IsWindow(Some(hwnd)) }.as_bool());
    assert_eq!(SHUTDOWN_IN_APARTMENT.get(), Some(true));
    assert!(
        !thread_in_apartment(),
        "all STA leases released on the owner"
    );
    // The coordinator may already be unwinding from a failed assertion.
    // Successful runs still require this receipt before joining the owner.
    let _ = receipts.send(Receipt::Retired);
}

fn receive(receipts: &Receiver<Receipt>) -> Receipt {
    receipts
        .recv_timeout(Duration::from_secs(10))
        .expect("native owner makes bounded progress")
}

fn uia_name(hwnd: usize) -> String {
    use windows::Win32::System::Com::{
        CLSCTX_INPROC_SERVER, COINIT_MULTITHREADED, CoCreateInstance, CoInitializeEx,
        CoUninitialize,
    };
    use windows::Win32::UI::Accessibility::{CUIAutomation, IUIAutomation};
    struct Apartment;
    impl Drop for Apartment {
        fn drop(&mut self) {
            // SAFETY: balanced with the successful initialization below,
            // after the client's interfaces have been released on this thread.
            unsafe { CoUninitialize() };
        }
    }
    // SAFETY: no borrowed pointer; balanced on this calling thread.
    unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) }
        .ok()
        .expect("UIA client MTA");
    let _apartment = Apartment;
    // SAFETY: a local COM client; HWND is a live target receipt, not an
    // interface transferred from an owner. UIA marshals its own calls.
    unsafe {
        let client: IUIAutomation =
            CoCreateInstance(&CUIAutomation, None, CLSCTX_INPROC_SERVER).expect("UIA client");
        let element = client
            .ElementFromHandle(HWND(hwnd as *mut _))
            .expect("UIA window provider");
        element.CurrentName().expect("UIA name").to_string()
    }
}

#[test]
fn two_win32_loops_keep_tsf_grants_and_retirement_on_their_owners() {
    // Commands disconnect before the scope joins on a failed assertion.
    // The owners then close their local windows and COM resources as on Stop.
    thread::scope(|scope| {
        let (a_tx, a_rx) = sync_channel(4);
        let (b_tx, b_rx) = sync_channel(4);
        let (a_report, a_receipts) = sync_channel(4);
        let (b_report, b_receipts) = sync_channel(4);
        let a = scope.spawn(move || run_owner("FLUI owner A", a_rx, a_report));
        let b = scope.spawn(move || run_owner("FLUI owner B", b_rx, b_report));
        let a_ready = receive(&a_receipts);
        let b_ready = receive(&b_receipts);
        match (&a_ready, &b_ready) {
            (
                Receipt::Ready {
                    thread: at,
                    hwnd: ah,
                    client: ac,
                },
                Receipt::Ready {
                    thread: bt,
                    hwnd: bh,
                    client: bc,
                },
            ) => {
                assert_ne!(at, bt);
                assert_ne!(ah, bh);
                assert_ne!(*ac, 0);
                assert_ne!(*bc, 0);
            }
            other => panic!("readiness: {other:?}"),
        }
        println!("two-loop readiness: {a_ready:?}; {b_ready:?}");
        let Receipt::Ready { hwnd: a_hwnd, .. } = a_ready else {
            unreachable!()
        };
        let Receipt::Ready { hwnd: b_hwnd, .. } = b_ready else {
            unreachable!()
        };
        assert_eq!(uia_name(a_hwnd), "FLUI owner A");
        assert_eq!(uia_name(b_hwnd), "FLUI owner B");
        for (sender, receipts) in [(&a_tx, &a_receipts), (&b_tx, &b_receipts)] {
            for (prevent, expected) in [
                (true, WindowMode::Normal),
                (false, WindowMode::Fullscreen),
                (false, WindowMode::Normal),
            ] {
                sender
                    .send(Command::Input { prevent })
                    .expect("input command");
                assert!(matches!(receive(receipts), Receipt::Input));
                sender.send(Command::WindowMode).expect("mode query");
                assert!(matches!(receive(receipts), Receipt::Mode(mode) if mode == expected));
            }
        }
        let (release, held) = sync_channel(1);
        a_tx.send(Command::Hold(held)).expect("hold A");
        assert!(matches!(receive(&a_receipts), Receipt::Held));
        assert_eq!(uia_name(b_hwnd), "FLUI owner B");
        b_tx.send(Command::Edit("B: 日本語 🦀".to_owned()))
            .expect("edit B");
        assert!(matches!(receive(&b_receipts), Receipt::Edited(text) if text == "B: 日本語 🦀"));
        assert!(
            matches!(a_receipts.try_recv(), Err(TryRecvError::Empty)),
            "A still held while B's actual TSF grant completed"
        );
        release.send(()).expect("release A");
        assert!(matches!(receive(&a_receipts), Receipt::Released));
        a_tx.send(Command::Edit("A: independent".to_owned()))
            .expect("edit A");
        assert!(matches!(receive(&a_receipts), Receipt::Edited(text) if text == "A: independent"));
        a_tx.send(Command::Stop).expect("stop A");
        assert!(matches!(receive(&a_receipts), Receipt::Retired));
        a.join().expect("A retired cleanly");
        assert_eq!(uia_name(b_hwnd), "FLUI owner B");
        b_tx.send(Command::Edit("B: after A retired".to_owned()))
            .expect("edit surviving B");
        assert!(
            matches!(receive(&b_receipts), Receipt::Edited(text) if text == "B: after A retired")
        );
        b_tx.send(Command::Stop).expect("stop B");
        assert!(matches!(receive(&b_receipts), Receipt::Retired));
        b.join().expect("B retired cleanly");
    });
}
