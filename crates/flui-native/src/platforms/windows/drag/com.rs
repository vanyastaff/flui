/// Run one vtable method's body; a panic answers `E_UNEXPECTED`.
fn com_boundary<R>(body: impl FnOnce() -> windows_core::Result<R>) -> windows_core::Result<R> {
    contain_os_entry("OLE drag and drop", body).unwrap_or_else(|| Err(E_UNEXPECTED.into()))
}

/// The `#[implement]` expansions, in a module of their own so the lints
/// their generated code trips are expected here and nowhere else.
#[expect(
    clippy::ref_as_ptr,
    clippy::inline_always,
    raw_borrows_via_references,
    reason = "code generated by windows-core's #[implement]"
)]
mod objects {
    use std::cell::{Cell, RefCell};
    use std::rc::Rc;
    use std::sync::Arc;

    use flui_foundation::DataTransferId;
    use flui_platform::data_transfer::TransferActions;
    use flui_platform::drag::OsDragProvider;
    use windows::Win32::System::Com::{IDataObject, IEnumFORMATETC};
    use windows::Win32::System::Ole::{IDropSource, IDropTarget};
    use windows_core::implement;

    use super::super::OleTransfer;
    use super::SourceEntry;
    use crate::platforms::windows::platform::WindowRef;

    // Every object here holds owner-thread state (`Rc`, `Cell`, `RefCell`, a
    // `!Send` provider): `Agile = false` withholds `IAgileObject` and the
    // free-threaded marshaler, so COM marshals another apartment's calls
    // back to the owner's instead of handing it the raw object.

    /// The data object of one outgoing session: its representations, served
    /// lazily through the session's provider.
    #[implement(IDataObject, Agile = false)]
    pub(in crate::platforms::windows) struct SourceData {
        pub(super) entries: Vec<SourceEntry>,
        /// Leased out while it runs, so a fetch from inside it is refused
        /// rather than reentering it.
        pub(super) provider: RefCell<Option<OsDragProvider>>,
    }

    /// The formats a [`SourceData`] offers, enumerated.
    #[implement(IEnumFORMATETC, Agile = false)]
    pub(in crate::platforms::windows) struct FormatList {
        pub(super) formats: Rc<[u16]>,
        pub(super) next: Cell<usize>,
    }

    /// Ends the modal loop when the buttons that began it are released.
    #[implement(IDropSource, Agile = false)]
    pub(in crate::platforms::windows) struct DropSource {
        pub(super) began: u32,
    }

    /// One window's drop target.
    #[implement(IDropTarget, Agile = false)]
    pub(in crate::platforms::windows) struct WindowDropTarget {
        pub(super) window: WindowRef,
        pub(super) transfer: Arc<OleTransfer>,
        /// The offer of the drag over the window, and what its source
        /// permitted at the last event.
        pub(super) over: Cell<Option<(DataTransferId, TransferActions)>>,
    }
}

/// One format a [`SourceData`] serves.
pub(super) struct SourceEntry {
    format: u16,
    native: NativeFormat,
    representation: RepresentationIndex,
    /// The identity's full media type: the backend serves it itself.
    identity: Option<Vec<u8>>,
}

impl SourceData {
    /// The data object of a session offering `representations`.
    pub(super) fn new(
        representations: &[RepresentationDescriptor],
        provider: OsDragProvider,
    ) -> Self {
        let mut entries: Vec<SourceEntry> = Vec::new();
        for (index, descriptor) in representations.iter().enumerate() {
            let Ok(index) = u16::try_from(index) else {
                break;
            };
            let native = native_format(&descriptor.format);
            let Some(format) = clipboard_format(&native) else {
                tracing::warn!(?descriptor.format, "no clipboard format; the representation is not offered");
                continue;
            };
            if entries.iter().any(|entry| entry.format == format) {
                continue;
            }
            // The identity format carries the identity's full media type.
            let identity = match (&native, &descriptor.format) {
                (
                    NativeFormat::Named(name),
                    flui_platform::data_transfer::TransferFormat::Custom { mime },
                ) if name == flui_platform::drag::IDENTITY_ESSENCE => {
                    Some(mime.as_str().as_bytes().to_vec())
                }
                _ => None,
            };
            entries.push(SourceEntry {
                format,
                native,
                representation: RepresentationIndex(index),
                identity,
            });
        }
        Self {
            entries,
            provider: RefCell::new(Some(provider)),
        }
    }

    fn entry(&self, format: *const FORMATETC) -> windows_core::Result<&SourceEntry> {
        // SAFETY: OLE passes a pointer to a `FORMATETC` live for the call, or
        // null, which `as_ref` refuses.
        let format = unsafe { format.as_ref() }.ok_or(E_POINTER)?;
        if format.dwAspect != DVASPECT_CONTENT.0 {
            return Err(DV_E_DVASPECT.into());
        }
        if format.tymed & (TYMED_HGLOBAL.0 as u32) == 0 {
            return Err(DV_E_TYMED.into());
        }
        self.entries
            .iter()
            .find(|entry| entry.format == format.cfFormat)
            .ok_or_else(|| DV_E_FORMATETC.into())
    }

    /// Serve `entry`'s bytes: the identity from the descriptor, everything
    /// else from the provider, run with no borrow held.
    fn serve(&self, entry: &SourceEntry) -> windows_core::Result<Vec<u8>> {
        if let Some(identity) = &entry.identity {
            return Ok(identity.clone());
        }
        let Some(mut provider) = self.provider.borrow_mut().take() else {
            // Asked from inside the provider itself, or after it panicked.
            return Err(E_UNEXPECTED.into());
        };
        let Some(served) = contain_os_entry("a drag's provider", || provider(entry.representation))
        else {
            // A provider that panicked is neither called again nor dropped:
            // it is retained and the slot stays empty, so every later fetch
            // is refused (ADR-0127 §2).
            std::mem::forget(provider);
            return Err(E_UNEXPECTED.into());
        };
        // Nothing refills the slot while the provider is leased out.
        let replaced = self.provider.borrow_mut().replace(provider);
        debug_assert!(replaced.is_none(), "BUG: the provider slot was refilled");
        crate::shared::panic_boundary::contain_owner_callback(|| drop(replaced));
        let payload = match served {
            Ok(payload) => payload,
            Err(error) => {
                tracing::debug!(%error, "the drag's provider refused a representation");
                return Err(DV_E_FORMATETC.into());
            }
        };
        encode(&entry.native, &payload).ok_or_else(|| DV_E_FORMATETC.into())
    }
}

impl Drop for SourceData {
    fn drop(&mut self) {
        // The last reference goes in `IUnknown::Release`, an `extern "system"`
        // function a panic cannot unwind out of: the provider's user captures
        // retire under the owner's containment instead of aborting.
        let provider = self.provider.get_mut().take();
        crate::shared::panic_boundary::contain_owner_callback(|| drop(provider));
    }
}

impl IDataObject_Impl for SourceData_Impl {
    fn GetData(&self, format: *const FORMATETC) -> windows_core::Result<STGMEDIUM> {
        com_boundary(|| {
            let entry = self.entry(format)?;
            let bytes = self.serve(entry)?;
            let global = write_global(&bytes)?;
            Ok(STGMEDIUM {
                tymed: TYMED_HGLOBAL.0 as u32,
                u: STGMEDIUM_0 { hGlobal: global },
                pUnkForRelease: ManuallyDrop::new(None),
            })
        })
    }

    fn GetDataHere(
        &self,
        _format: *const FORMATETC,
        _medium: *mut STGMEDIUM,
    ) -> windows_core::Result<()> {
        Err(E_NOTIMPL.into())
    }

    fn QueryGetData(&self, format: *const FORMATETC) -> HRESULT {
        com_boundary(|| self.entry(format).map(|_| ())).map_or_else(|error| error.code(), |()| S_OK)
    }

    fn GetCanonicalFormatEtc(&self, _in: *const FORMATETC, out: *mut FORMATETC) -> HRESULT {
        // SAFETY: OLE passes a writable `FORMATETC`, or null.
        if let Some(out) = unsafe { out.as_mut() } {
            out.ptd = std::ptr::null_mut();
        }
        DATA_S_SAMEFORMATETC
    }

    fn SetData(
        &self,
        _format: *const FORMATETC,
        _medium: *const STGMEDIUM,
        _release: BOOL,
    ) -> windows_core::Result<()> {
        Err(E_NOTIMPL.into())
    }

    fn EnumFormatEtc(&self, direction: u32) -> windows_core::Result<IEnumFORMATETC> {
        com_boundary(|| {
            if direction != DATADIR_GET.0 as u32 {
                return Err(E_NOTIMPL.into());
            }
            let formats: Rc<[u16]> = self.entries.iter().map(|entry| entry.format).collect();
            Ok(FormatList {
                formats,
                next: Cell::new(0),
            }
            .into())
        })
    }

    fn DAdvise(
        &self,
        _format: *const FORMATETC,
        _advf: u32,
        _sink: Ref<'_, IAdviseSink>,
    ) -> windows_core::Result<u32> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }

    fn DUnadvise(&self, _connection: u32) -> windows_core::Result<()> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }

    fn EnumDAdvise(&self) -> windows_core::Result<IEnumSTATDATA> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }
}

impl IEnumFORMATETC_Impl for FormatList_Impl {
    fn Next(&self, count: u32, out: *mut FORMATETC, fetched: *mut u32) -> HRESULT {
        let start = self.next.get().min(self.formats.len());
        let wanted = usize::try_from(count).unwrap_or(usize::MAX);
        let take = wanted.min(self.formats.len() - start);
        if take > 0 && out.is_null() {
            return E_POINTER;
        }
        for (offset, format) in self.formats[start..start + take].iter().enumerate() {
            // SAFETY: OLE passes room for `count` entries; `offset < take <= count`.
            unsafe { out.add(offset).write(global_format(*format)) };
        }
        self.next.set(start + take);
        // SAFETY: OLE passes a writable count, or null when it asks for one entry.
        if let Some(fetched) = unsafe { fetched.as_mut() } {
            *fetched = u32::try_from(take).unwrap_or(u32::MAX);
        }
        if take == wanted { S_OK } else { S_FALSE }
    }

    fn Skip(&self, count: u32) -> windows_core::Result<()> {
        let skipped = self
            .next
            .get()
            .saturating_add(usize::try_from(count).unwrap_or(usize::MAX));
        self.next.set(skipped.min(self.formats.len()));
        Ok(())
    }

    fn Reset(&self) -> windows_core::Result<()> {
        self.next.set(0);
        Ok(())
    }

    fn Clone(&self) -> windows_core::Result<IEnumFORMATETC> {
        Ok(FormatList {
            formats: Rc::clone(&self.formats),
            next: Cell::new(self.next.get()),
        }
        .into())
    }
}

impl DropSource {
    /// A drop source for a drag that the mouse buttons `began` (`MK_*`) hold.
    pub(super) const fn new(began: u32) -> Self {
        Self { began }
    }
}

impl IDropSource_Impl for DropSource_Impl {
    fn QueryContinueDrag(&self, escape: BOOL, keys: MODIFIERKEYS_FLAGS) -> HRESULT {
        match continue_drag(escape.as_bool(), keys.0, self.began) {
            DragContinuation::Continue => S_OK,
            DragContinuation::Drop => DRAGDROP_S_DROP,
            DragContinuation::Cancel => DRAGDROP_S_CANCEL,
        }
    }

    fn GiveFeedback(&self, _effect: DROPEFFECT) -> HRESULT {
        DRAGDROP_S_USEDEFAULTCURSORS
    }
}

impl WindowDropTarget {
    /// The drop target of `window`.
    pub(in crate::platforms::windows) fn new(
        window: WindowRef,
        transfer: Arc<OleTransfer>,
    ) -> Self {
        Self {
            window,
            transfer,
            over: Cell::new(None),
        }
    }

    /// Deliver `event` to the window, its position given in screen device
    /// pixels and converted to the window's logical pixels.
    fn dispatch(
        &self,
        event: impl FnOnce(Option<Point<f64>>) -> Option<DragDropEvent>,
        screen: Option<&POINTL>,
    ) {
        let hwnd = self.window.hwnd();
        let _ = self.window.with_context("drag and drop", |context| {
            let position = screen.and_then(|screen| {
                let mut point = POINT {
                    x: screen.x,
                    y: screen.y,
                };
                // SAFETY: the live window this context belongs to, on its
                // thread; `point` is a live local the call rewrites.
                unsafe { ScreenToClient(hwnd, &raw mut point) }
                    .as_bool()
                    .then(|| {
                        let scale = context.scale_factor.get();
                        Point::new(f64::from(point.x) / scale, f64::from(point.y) / scale)
                    })
            });
            // Dispatch is the window's own: it queues behind a callback
            // already running and contains the callback's panics.
            if let Some(event) = event(position) {
                context
                    .callbacks
                    .dispatch_input(PlatformInput::DragDrop(event));
            }
        });
    }

    /// The effect to answer the OS with: the cached feedback, narrowed.
    fn answer(&self, id: DataTransferId, allowed: TransferActions) -> DROPEFFECT {
        self.transfer
            .feedback(id)
            .resolve(allowed)
            .map_or(DROPEFFECT_NONE, |action| DROPEFFECT(effect_bits(action)))
    }

    /// The drag left the window (or its window is going): the offer is
    /// left and retired.
    pub(in crate::platforms::windows) fn leave(&self) {
        if let Some((id, _)) = self.over.take() {
            self.dispatch(|_| Some(DragDropEvent::Exited { id }), None);
            self.transfer.close_offer(id);
        }
    }
}

/// The in/out effect OLE passes a target method.
fn effect_slot<'a>(effect: *mut DROPEFFECT) -> windows_core::Result<&'a mut DROPEFFECT> {
    // SAFETY: OLE passes a pointer to its `DROPEFFECT`, live and writable for
    // the call, or null, which `as_mut` refuses.
    unsafe { effect.as_mut() }.ok_or_else(|| E_POINTER.into())
}

impl IDropTarget_Impl for WindowDropTarget_Impl {
    fn DragEnter(
        &self,
        data: Ref<'_, IDataObject>,
        _keys: MODIFIERKEYS_FLAGS,
        point: &POINTL,
        effect: *mut DROPEFFECT,
    ) -> windows_core::Result<()> {
        com_boundary(|| {
            let effect = effect_slot(effect)?;
            let allowed = actions_of(effect.0);
            *effect = DROPEFFECT_NONE;
            // A drag entering without the last one having left.
            self.leave();
            let Some(object) = data.cloned() else {
                return Ok(());
            };
            let offered = describe(&object);
            let Some(offer) = self.transfer.open_offer(object, offered) else {
                return Ok(());
            };
            let id = offer.id();
            self.over.set(Some((id, allowed)));
            self.dispatch(
                |position| {
                    Some(DragDropEvent::Entered {
                        offer,
                        allowed,
                        position,
                    })
                },
                Some(point),
            );
            // The window may have been left (or closed) from inside its callback.
            if self.over.get().is_some_and(|(over, _)| over == id) {
                *effect = self.answer(id, allowed);
            }
            Ok(())
        })
    }

    fn DragOver(
        &self,
        _keys: MODIFIERKEYS_FLAGS,
        point: &POINTL,
        effect: *mut DROPEFFECT,
    ) -> windows_core::Result<()> {
        com_boundary(|| {
            let effect = effect_slot(effect)?;
            let allowed = actions_of(effect.0);
            *effect = DROPEFFECT_NONE;
            let Some((id, _)) = self.over.get() else {
                return Ok(());
            };
            self.over.set(Some((id, allowed)));
            // A point the window cannot place is no movement: the window
            // keeps the position it was last told, and the OS is still
            // answered from the cached feedback below.
            self.dispatch(
                |position| {
                    position.map(|position| DragDropEvent::Moved {
                        id,
                        allowed,
                        position,
                    })
                },
                Some(point),
            );
            if self.over.get().is_some_and(|(over, _)| over == id) {
                *effect = self.answer(id, allowed);
            }
            Ok(())
        })
    }

    fn DragLeave(&self) -> windows_core::Result<()> {
        com_boundary(|| {
            self.leave();
            Ok(())
        })
    }

    fn Drop(
        &self,
        _data: Ref<'_, IDataObject>,
        _keys: MODIFIERKEYS_FLAGS,
        point: &POINTL,
        effect: *mut DROPEFFECT,
    ) -> windows_core::Result<()> {
        com_boundary(|| {
            let effect = effect_slot(effect)?;
            let allowed = actions_of(effect.0);
            *effect = DROPEFFECT_NONE;
            let Some((id, _)) = self.over.get() else {
                return Ok(());
            };
            // The action comes from what the target last cached, never from
            // the drop itself; a refusal leaves instead of dropping.
            let Some(action) = self.transfer.feedback(id).resolve(allowed) else {
                self.leave();
                return Ok(());
            };
            // The offer stays open until the target concludes it.
            self.over.set(None);
            *effect = DROPEFFECT(effect_bits(action));
            self.dispatch(
                |position| {
                    Some(DragDropEvent::Dropped {
                        id,
                        action,
                        position,
                    })
                },
                Some(point),
            );
            Ok(())
        })
    }
}
