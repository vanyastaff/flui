//! The `cfg` conditions the core host names in many places, each spelled once, and the
//! application's floor the CLI hands to the build.

fn main() {
    app_floor();
    cfg_aliases::cfg_aliases! {
        // The winit host, on the targets it builds for.
        winit_host: {
            all(
                feature = "winit-backend",
                any(target_os = "windows", target_os = "macos", target_os = "linux")
            )
        },
        // The native Wayland host.
        wayland_host: { all(target_os = "linux", feature = "wayland") },
        // The native X11 host.
        x11_host: { all(target_os = "linux", feature = "x11") },
        // A Linux host whose loop reads the session's own sources: the
        // Settings portal, logind and memory pressure. A Linux host joins it
        // here by its feature.
        linux_host: {
            all(
                target_os = "linux",
                any(feature = "winit-backend", feature = "wayland", feature = "x11")
            )
        },
    }
}

/// The application's floor (ADR-0244 §10): `flui build` and `flui run` hand
/// each `[platforms.<environment>] min` of `flui.toml` to the build as
/// `FLUI_APP_MIN_<ENVIRONMENT>`, and the platform refuses to start below the
/// higher of it and FLUI's floor. A plain `cargo build` sets none, so only
/// FLUI's floor applies there.
fn app_floor() {
    use std::fmt::Write as _;

    let out_dir = std::env::var_os("OUT_DIR").expect("BUG: cargo sets OUT_DIR for a build script");
    let mut source = String::from(
        "// Generated by build.rs from the `FLUI_APP_MIN_<ENVIRONMENT>` variables `flui build`\n\
         // sets from flui.toml; `None` where the application states no floor.\n",
    );
    for (variable, cfg, name, kind) in [
        (
            "FLUI_APP_MIN_WINDOWS",
            "any(windows, test)",
            "WINDOWS",
            Kind::Number,
        ),
        (
            "FLUI_APP_MIN_MACOS",
            "any(target_os = \"macos\", test)",
            "MACOS",
            Kind::Release,
        ),
        (
            "FLUI_APP_MIN_IOS",
            "any(target_os = \"ios\", test)",
            "IOS",
            Kind::Release,
        ),
        (
            "FLUI_APP_MIN_ANDROID",
            "any(target_os = \"android\", test)",
            "ANDROID",
            Kind::Number,
        ),
    ] {
        println!("cargo::rerun-if-env-changed={variable}");
        let value = std::env::var(variable)
            .ok()
            .filter(|value| !value.trim().is_empty());
        let (ty, literal) = match (kind, value) {
            (Kind::Number, None) => ("u32", "None".to_owned()),
            (Kind::Release, None) => ("(u32, u32, u32)", "None".to_owned()),
            (Kind::Number, Some(value)) => (
                "u32",
                format!(
                    "Some({})",
                    value.trim().parse::<u32>().unwrap_or_else(|_| panic!(
                        "{variable} = {value:?} is not a number; `flui build` sets it from \
                         flui.toml's [platforms] min"
                    ))
                ),
            ),
            (Kind::Release, Some(value)) => {
                let (major, minor, patch) = release(&value).unwrap_or_else(|| {
                    panic!(
                        "{variable} = {value:?} is not a release like \"15.0\"; `flui build` \
                         sets it from flui.toml's [platforms] min"
                    )
                });
                (
                    "(u32, u32, u32)",
                    format!("Some(({major}, {minor}, {patch}))"),
                )
            }
        };
        write!(
            source,
            "\n#[cfg({cfg})]\npub(crate) const {name}: Option<{ty}> = {literal};\n"
        )
        .expect("BUG: writing to a String");
    }
    std::fs::write(std::path::Path::new(&out_dir).join("app_floor.rs"), source)
        .expect("BUG: OUT_DIR is writable");
}

#[derive(Clone, Copy)]
enum Kind {
    /// A Windows build or an Android API level.
    Number,
    /// A dotted Apple release.
    Release,
}

/// `"15"`, `"15.4"` or `"15.4.1"` as (major, minor, patch).
fn release(text: &str) -> Option<(u32, u32, u32)> {
    let mut parts = text.trim().split('.');
    let mut next = |required: bool| match parts.next() {
        Some(part) => part.parse::<u32>().ok(),
        None => (!required).then_some(0),
    };
    let release = (next(true)?, next(false)?, next(false)?);
    parts.next().is_none().then_some(release)
}
