//! Codegen: the Rust test a trace replays as, written by [`codegen()`].

use std::fmt::Write as _;

use flui_protocol::locator::{Locator, TextMatch};
use flui_protocol::method::{self, Method as _};
use flui_protocol::wait::{Condition, Expectation};
use serde_json::Value;

use super::format::CommandRow;
use super::reader::Trace;
use crate::error::{Error, Result};

/// What a generated test is called and how it starts its app.
#[derive(Debug, Clone, PartialEq, Eq)]
#[must_use]
pub struct CodegenOptions {
    test_name: String,
    launch: String,
}

impl CodegenOptions {
    /// A test named `test_name` that launches its app with the Rust expression `launch`, a
    /// [`Launch`](crate::Launch) (`Launch::headless(app)`, `Launch::cargo_example("gallery")`).
    pub fn new(test_name: impl Into<String>, launch: impl Into<String>) -> Self {
        Self {
            test_name: test_name.into(),
            launch: launch.into(),
        }
    }
}

/// The Rust test `trace` replays as (ADR-0241 §6): the commands that act, written against the
/// driver's API, and the waits that assert, written as expectations.
///
/// - A gesture on a locator in the main window becomes `driver.main_window()?.locate(…).tap()?`,
///   its locator a builder when it names only an identifier and text matches, and the gesture's
///   own arguments (text, keys) as written.
/// - A wait for a locator's name or value, its count or its absence becomes an `expect`.
/// - Any other command that acts is sent as recorded, through `Driver::call_value`, its strings as
///   Rust literals; the file's header then says it needs `serde_json`.
/// - Reads are left out: they change nothing, and the test reads what it asserts.
/// - A command codegen cannot write (one not in the protocol's method table yet, a pixel check
///   among them; a session's start or end) is a `// not generated:` line where it was sent, and
///   the header counts them, so the reader sees what the test leaves out. A replay skips the same
///   commands and lists them.
///
/// Locators are never resolved to coordinates or handles, so the test finds the elements again.
/// A redacted trace writes its redacted text as recorded; a trace recorded with `keep_text`
/// types what was typed.
///
/// # Errors
///
/// [`Error::InvalidArgument`] for a test name that is not a Rust identifier.
pub fn codegen(trace: &Trace, options: &CodegenOptions) -> Result<String> {
    let name = &options.test_name;
    let identifier = name
        .chars()
        .next()
        .is_some_and(|c| c == '_' || c.is_ascii_alphabetic())
        && name.chars().all(|c| c == '_' || c.is_ascii_alphanumeric());
    if !identifier {
        return Err(Error::invalid_argument(format!(
            "a test's name is a Rust identifier, not `{name}`"
        )));
    }
    let app = trace.header().target.app.as_deref().unwrap_or("the app");
    let mut body = String::new();
    let mut uses_expect = false;
    let mut not_generated = 0_u64;
    let main = main_window(trace);
    for step in trace.steps() {
        let line = match statement(step.command, main.as_deref()) {
            Statement::Read => continue,
            Statement::Code { line, expects } => {
                uses_expect |= expects;
                line
            }
            Statement::NotGenerated(reason) => {
                not_generated += 1;
                format!(
                    "// not generated: {} (seq {}): {reason}",
                    step.command.method, step.command.seq
                )
            }
        };
        body.push_str("    ");
        body.push_str(&line);
        body.push('\n');
    }
    let mut names = vec!["Driver"];
    if options.launch.contains("Launch::") {
        names.push("Launch");
    }
    if body.contains("Locator::") {
        names.push("Locator");
    }
    if body.contains("TextMatch::") {
        names.push("TextMatch");
    }
    if uses_expect {
        names.push("expect");
    }
    let mut out = String::new();
    let _ = writeln!(
        out,
        "//! Generated by `flui_driver::trace::codegen` from a trace of {app}: edit freely."
    );
    if body.contains("serde_json::") {
        out.push_str(
            "//! It sends some commands as recorded, so it needs `serde_json` as a \
             dev-dependency.\n",
        );
    }
    if not_generated > 0 {
        let _ = writeln!(
            out,
            "//! Not generated: {not_generated} command(s), each marked `// not generated:` where it \
             was sent; the test does not do what they did."
        );
    }
    out.push('\n');
    if let [only] = names.as_slice() {
        let _ = writeln!(out, "use flui_driver::{only};");
    } else {
        let _ = writeln!(out, "use flui_driver::{{{}}};", names.join(", "));
    }
    out.push_str("\n#[test]\n");
    let _ = writeln!(out, "fn {name}() -> flui_driver::Result<()> {{");
    let _ = writeln!(
        out,
        "    let mut driver = Driver::launch({})?;",
        options.launch
    );
    out.push_str(&body);
    out.push_str("    Ok(())\n}\n");
    Ok(out)
}

/// What a command becomes in the test.
enum Statement {
    /// Nothing: a read or an annotation changes nothing of the app.
    Read,
    /// A statement, and whether it uses `expect`.
    Code { line: String, expects: bool },
    /// A marked line, and why it is not code.
    NotGenerated(&'static str),
}

/// The statement `command` becomes.
fn statement(command: &CommandRow, main: Option<&str>) -> Statement {
    let Some(row) = method::find(&command.method) else {
        // The pixel commands until their rows join the method table with the front ends: a
        // replay lists them as skipped for the same reason, and the test says where they were.
        return Statement::NotGenerated(
            "not a method of the protocol's table yet, which a replay skips too",
        );
    };
    if command.method == method::WaitUntil::NAME {
        if let Some(line) = expectation(&command.params) {
            return Statement::Code {
                line,
                expects: true,
            };
        }
    } else if !row.effect.changes_app() {
        return Statement::Read;
    } else if row.name.starts_with("session.") {
        return Statement::NotGenerated("it begins or ends a session, which the test holds");
    }
    let line = gesture(&command.method, &command.params).unwrap_or_else(|| {
        let mut uses_window = false;
        let params = json_code(&command.params, main, false, &mut uses_window);
        let call = format!(
            "driver.call_value({:?}, serde_json::json!({params}))?;",
            command.method
        );
        if uses_window {
            format!("let window = driver.main_window()?.id();\n    {call}")
        } else {
            call
        }
    });
    Statement::Code {
        line,
        expects: false,
    }
}

/// The main window's handle in the trace: the first one `windows.list` answered.
fn main_window(trace: &Trace) -> Option<String> {
    trace.steps().into_iter().find_map(|step| {
        (step.command.method == method::WindowsList::NAME)
            .then(|| step.result?.ok.as_ref()?.get("windows")?.get(0)?.as_str())
            .flatten()
            .map(str::to_owned)
    })
}

/// `value` in `serde_json::json!`'s syntax, each string a Rust literal (control characters
/// escaped as Rust spells them, which JSON's `\u0001` is not). The recorded main window's handle
/// (`main`), where a `window` field holds it, is the test's own main window instead, a variable
/// `window` that `uses_window` says the statement needs: handles are the run's, not the trace's.
fn json_code(value: &Value, main: Option<&str>, in_window: bool, uses_window: &mut bool) -> String {
    match value {
        Value::Null => "null".to_owned(),
        Value::Bool(flag) => flag.to_string(),
        Value::Number(number) => number.to_string(),
        Value::String(text) if in_window && main == Some(text.as_str()) => {
            *uses_window = true;
            "window".to_owned()
        }
        Value::String(text) => format!("{text:?}"),
        Value::Array(items) => {
            let items: Vec<String> = items
                .iter()
                .map(|item| json_code(item, main, false, uses_window))
                .collect();
            format!("[{}]", items.join(", "))
        }
        Value::Object(fields) => {
            let fields: Vec<String> = fields
                .iter()
                .map(|(key, value)| {
                    let code = json_code(value, main, key == "window", uses_window);
                    format!("{key:?}: {code}")
                })
                .collect();
            format!("{{{}}}", fields.join(", "))
        }
    }
}

/// A gesture on a locator, as the API writes it.
fn gesture(method: &str, params: &Value) -> Option<String> {
    let fields = params.as_object()?;
    let locator = fields.get("target")?.get("locator")?;
    let locator = locator_code(locator)?;
    let only = |allowed: &[&str]| {
        fields
            .keys()
            .all(|key| key == "target" || allowed.contains(&key.as_str()))
    };
    let call = match method {
        _ if method == method::ElementTap::NAME && only(&[]) => "tap()".to_owned(),
        _ if method == method::ElementDoubleTap::NAME && only(&[]) => "double_tap()".to_owned(),
        _ if method == method::ElementScrollIntoView::NAME && only(&[]) => {
            "scroll_into_view()".to_owned()
        }
        _ if method == method::ElementTypeText::NAME && only(&["text"]) => {
            format!("type_text({:?})", fields.get("text")?.as_str()?)
        }
        _ if method == method::ElementPressKeys::NAME && only(&["keys"]) => {
            let keys: Vec<String> = fields
                .get("keys")?
                .as_array()?
                .iter()
                .map(|key| key.as_str().map(|key| format!("{key:?}")))
                .collect::<Option<_>>()?;
            format!("press_keys(&[{}])", keys.join(", "))
        }
        _ => return None,
    };
    Some(format!("driver.main_window()?.locate({locator}).{call}?;"))
}

/// A wait that asserts, as an `expect`.
fn expectation(params: &Value) -> Option<String> {
    let fields = params.as_object()?;
    let allowed = ["window", "condition", "timeout_ms"];
    if !fields.keys().all(|key| allowed.contains(&key.as_str())) {
        return None;
    }
    let condition: Condition = serde_json::from_value(fields.get("condition")?.clone()).ok()?;
    let timeout = fields
        .get("timeout_ms")
        .and_then(Value::as_u64)
        .map_or_default(|ms| format!(".timeout(std::time::Duration::from_millis({ms}))"));
    let (locator, assertion) = match condition {
        Condition::Gone(locator) => (locator, "to_be_gone()".to_owned()),
        Condition::Matches { locator, expect } => {
            let assertion = match expect {
                Expectation::Name(TextMatch::Exact {
                    text,
                    ignore_case: false,
                }) => format!("to_have_name({text:?})"),
                Expectation::Value(TextMatch::Exact {
                    text,
                    ignore_case: false,
                }) => format!("to_have_value({text:?})"),
                Expectation::Count(count) => format!("to_have_count({count})"),
                _ => return None,
            };
            (locator, assertion)
        }
        _ => return None,
    };
    let locator = locator_code(&serde_json::to_value(locator).ok()?)?;
    Some(format!(
        "expect(driver.main_window()?.locate({locator})){timeout}.{assertion}?;"
    ))
}

/// A locator as builder calls, when it names only an identifier and text matches; the window
/// it was resolved in is left to `main_window`.
fn locator_code(value: &Value) -> Option<String> {
    let mut value = value.clone();
    if let Some(fields) = value.as_object_mut() {
        fields.remove("window");
    }
    let locator: Locator = serde_json::from_value(value.clone()).ok()?;
    let fields = value.as_object()?;
    let allowed = ["identifier", "name", "value", "description"];
    if fields.is_empty() || !fields.keys().all(|key| allowed.contains(&key.as_str())) {
        return None;
    }
    let mut code = match (&locator.identifier, &locator.name) {
        (Some(identifier), _) => format!("Locator::identifier({identifier:?})"),
        (
            None,
            Some(TextMatch::Exact {
                text,
                ignore_case: false,
            }),
        ) => format!("Locator::named({text:?})"),
        (None, Some(name)) => format!("Locator::default().name_matching({})", text_match(name)?),
        (None, None) => "Locator::default()".to_owned(),
    };
    if locator.identifier.is_some()
        && let Some(name) = &locator.name
    {
        let _ = write!(code, ".name_matching({})", text_match(name)?);
    }
    if let Some(value) = &locator.value {
        let _ = write!(code, ".value({})", text_match(value)?);
    }
    if let Some(description) = &locator.description {
        let _ = write!(code, ".description({})", text_match(description)?);
    }
    Some(code)
}

/// A text match as its constructor.
fn text_match(text: &TextMatch) -> Option<String> {
    let (constructor, needle, ignore_case) = match text {
        TextMatch::Exact { text, ignore_case } => ("exact", text, *ignore_case),
        TextMatch::Contains { text, ignore_case } => ("contains", text, *ignore_case),
        TextMatch::Prefix { text, ignore_case } => ("prefix", text, *ignore_case),
        _ => return None,
    };
    let case = if ignore_case { ".ignoring_case()" } else { "" };
    Some(format!("TextMatch::{constructor}({needle:?}){case}"))
}
