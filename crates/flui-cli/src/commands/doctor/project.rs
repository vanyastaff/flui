//! The project section of `flui doctor`: what the crates the project links
//! declare for its manifests (ADR-0307), and whether a manifest FLUI does
//! not write carries it.
//!
//! Check ids are stable, for agents and CI reading `--json`:
//! `project.declarations` (the graph's declarations read), `project.android-manifest`
//! (the project's own Android manifest) and `project.manifest` (one per
//! `--manifest` path, the path in the event's `path`).

use std::path::{Path, PathBuf};

use super::{Check, Fix, Status};
use crate::build::android_manifest;
use crate::declarations::Declarations;
use crate::declarations::verify::{Manifest, ManifestKind, Missing};

const SECTION: &str = "project";

/// The note on an Android manifest that is not Gradle's merged one.
const NOT_MERGED: &str = "checked as written, not as Gradle's merged manifest: entries that \
                          library manifests merge in are not seen";

/// The project checks for `dir`: the declarations and the project's own
/// Android manifest when `dir` is a FLUI project, then each of `manifests`.
pub(super) fn project_checks(dir: &Path, manifests: &[PathBuf]) -> Vec<Check> {
    let mut checks = Vec::new();
    if dir.join("flui.toml").is_file() {
        checks.push(declarations_check(dir));
        if dir.join("platforms").join("android").is_dir() {
            checks.push(android_manifest_check(dir));
        }
    }
    for path in manifests {
        checks.push(manifest_check(dir, path).with_path(Some(path.clone())));
    }
    checks
}

fn declarations_check(dir: &Path) -> Check {
    const ID: &str = "project.declarations";
    const TITLE: &str = "Manifest declarations";
    let targets: Vec<&str> = [ManifestKind::Android, ManifestKind::ApplePrivacy]
        .into_iter()
        .flat_map(ManifestKind::targets)
        .copied()
        .collect();
    match Declarations::collect(dir, &targets) {
        Ok(declarations) => {
            let permissions = declarations.android_permissions().count();
            let reasons: usize = declarations
                .apple_accessed_apis()
                .map(|(_, reasons)| reasons.len())
                .sum();
            Check::ok(
                ID,
                SECTION,
                TITLE,
                format!(
                    "{permissions} Android permission(s), {reasons} Apple accessed-API reason(s)"
                ),
            )
        }
        Err(error) => Check::failing(
            ID,
            SECTION,
            TITLE,
            Status::Error,
            error.to_string(),
            Some(Fix::manual(
                "correct the crate's [package.metadata.flui.declares]; `flui build` refuses it too",
            )),
        ),
    }
}

fn android_manifest_check(dir: &Path) -> Check {
    const ID: &str = "project.android-manifest";
    const TITLE: &str = "Android manifest";
    let path = android_manifest::path_in(dir);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            return Check::ok(ID, SECTION, TITLE, "`flui build` generates it".to_owned());
        }
        Err(error) => {
            return Check::failing(
                ID,
                SECTION,
                TITLE,
                Status::Error,
                format!("cannot read it: {error}"),
                None,
            )
            .with_path(Some(path));
        }
    };
    if android_manifest::is_generated(&text) {
        return Check::ok(
            ID,
            SECTION,
            TITLE,
            "generated by `flui build`, which rewrites it on every build".to_owned(),
        )
        .with_path(Some(path));
    }
    let lacks = Manifest::parse(text.as_bytes())
        .and_then(|manifest| {
            let declarations = Declarations::collect(dir, ManifestKind::Android.targets())
                .map_err(|error| error.to_string())?;
            Ok(manifest.missing(&declarations))
        })
        .map_or_else(
            |reason| format!("; it {reason}"),
            |missing| lacking(&missing),
        );
    Check::failing(
        ID,
        SECTION,
        TITLE,
        Status::Error,
        format!("not written by `flui build`, which refuses it{lacks}"),
        Some(Fix::manual(
            "move what you added into flui.toml or a crate's declarations, delete the file, and \
             build again: `flui build` generates it (ADR-0307)",
        )),
    )
    .with_path(Some(path))
    .with_note(NOT_MERGED)
}

fn manifest_check(dir: &Path, path: &Path) -> Check {
    const ID: &str = "project.manifest";
    const TITLE: &str = "Manifest";
    let failing = |detail: String, fix: Option<Fix>| {
        Check::failing(ID, SECTION, TITLE, Status::Error, detail, fix)
    };
    let manifest = match std::fs::read(path)
        .map_err(|error| format!("cannot be read: {error}"))
        .and_then(|bytes| Manifest::parse(&bytes))
    {
        Ok(manifest) => manifest,
        Err(reason) => return failing(format!("the file {reason}"), None),
    };
    let declarations = match Declarations::collect(dir, manifest.kind().targets()) {
        Ok(declarations) => declarations,
        Err(error) => return failing(error.to_string(), None),
    };
    let missing = manifest.missing(&declarations);
    let check = if missing.is_empty() {
        Check::ok(
            ID,
            SECTION,
            TITLE,
            "declares everything the linked crates declare".to_owned(),
        )
    } else {
        let lines: Vec<&str> = missing
            .iter()
            .map(|missing| missing.line.as_str())
            .collect();
        failing(
            format!("lacks {}", entries(&missing)),
            Some(Fix::manual(format!("add {}", lines.join("; ")))),
        )
    };
    let merged = path.components().any(|component| {
        component
            .as_os_str()
            .to_str()
            .is_some_and(|name| name.starts_with("merged_manifest"))
    });
    if manifest.kind() == ManifestKind::Android && !merged {
        check.with_note(NOT_MERGED)
    } else {
        check
    }
}

/// `"; it lacks …"`, or nothing when `missing` is empty.
fn lacking(missing: &[Missing]) -> String {
    if missing.is_empty() {
        String::new()
    } else {
        format!("; it lacks {}", entries(missing))
    }
}

/// Each missing entry with the crates that declare it.
fn entries(missing: &[Missing]) -> String {
    let entries: Vec<String> = missing.iter().map(ToString::to_string).collect();
    entries.join(", ")
}
