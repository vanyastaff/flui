//! State-preserving hot-reload project template.
//!
//! Emits the three-crate host/worker/types layout the reload protocol requires
//! (see `docs/hot-reload.md`): the host
//! binary owns the element tree — and therefore every `State` — while the
//! reloadable worker `cdylib` holds only the `build()` implementations, so a
//! code change to the worker preserves state across a reload.
//!
//! The generated project is a workspace because cargo must be able to build the
//! worker and the host independently: `flui run` watches the worker crate and
//! rebuilds only it, leaving the running host untouched.
//!
//! Reload is a development build only. The host's default `linked` feature
//! links the logic crate and calls its build function directly, so a release
//! build installs no hook and the package's loader and watcher are dead code.
//! `flui run` builds the host with its `reload` feature and without the
//! default ones (`[hot_reload] reload_feature`), so the running host links no
//! copy of the logic crate and is not relinked when it changes.

use super::{DependencySource, FrameworkPackage, ProjectPlan};

/// The host feature `flui run` builds with: the hook that loads and reloads
/// the logic crate's library.
const RELOAD_FEATURE: &str = "reload";

/// A dependency on a sibling crate inside the generated workspace.
fn member_dep(sibling: &str) -> String {
    member_dep_table(sibling).to_string()
}

/// A sibling dependency that a feature turns on.
fn optional_member_dep(sibling: &str) -> String {
    let mut dependency = member_dep_table(sibling);
    if let toml::Value::Table(table) = &mut dependency {
        table.insert(String::from("optional"), toml::Value::Boolean(true));
    }
    dependency.to_string()
}

fn member_dep_table(sibling: &str) -> toml::Value {
    let mut dependency = toml::Table::new();
    dependency.insert(
        String::from("path"),
        toml::Value::String(format!("../{sibling}")),
    );
    toml::Value::Table(dependency)
}

pub fn generate(name: &str, app_id: &str, source: &DependencySource) -> ProjectPlan {
    let lib_name = name.replace('-', "_");
    let types_package = format!("{name}-types");
    let worker_package = format!("{name}-logic");
    let host_package = format!("{name}-host");
    let worker_lib = format!("{lib_name}_logic");

    ProjectPlan::new()
        .file(
            "Cargo.toml",
            root_workspace(&types_package, &worker_package, &host_package),
        )
        .file(
            "flui.toml",
            flui_config(name, app_id, &host_package, &worker_package, &worker_lib),
        )
        .file(
            "README.md",
            readme(name, &types_package, &worker_package, &host_package),
        )
        .merge(types_plan(&types_package, source))
        .merge(logic_plan(
            &types_package,
            &worker_package,
            &worker_lib,
            source,
        ))
        .merge(host_plan(
            name,
            &types_package,
            &host_package,
            &worker_package,
            &worker_lib,
            source,
        ))
}

fn root_workspace(types_package: &str, worker_package: &str, host_package: &str) -> String {
    let version = env!("CARGO_PKG_VERSION");
    let profiles = super::PROFILES;
    format!(
        r#"# FLUI hot-reload workspace (generated by `flui create --hot-reload` v{version}).
#
# Three crates, one workspace:
#   {types_package}/  — shared types + persistent State (linked into host + worker)
#   {worker_package}/ — reloadable build() code (cdylib; the reload target)
#   {host_package}/   — window, GPU, element tree; loads the worker (bin)
[workspace]
resolver = "3"
members = ["{types_package}", "{worker_package}", "{host_package}"]

[workspace.package]
version = "0.1.0"
edition = "2024"
rust-version = "1.99"

[workspace.dependencies]
tracing = "0.1"

{profiles}"#
    )
}

fn flui_config(
    name: &str,
    app_id: &str,
    host_package: &str,
    worker_package: &str,
    worker_lib: &str,
) -> String {
    // `logic_watch` / `types_watch` are relative to this `flui.toml`, and name
    // the directories whose edits trigger a worker rebuild (hot reload) versus
    // a host restart (hot restart, because the type layout changed).
    let types_package = format!("{name}-types");
    format!(
        r#"[app]
name = "{name}"
version = "0.1.0"
id = "{app_id}"

[build]
target_platforms = ["windows", "linux", "macos"]

[assets]
directories = ["assets"]

# `flui run` reads this section and drives the worker rebuild loop. Deleting it
# degrades `flui run` to a process-restart watcher (no state preservation).
[hot_reload]
host_package = "{host_package}"
worker_package = "{worker_package}"
worker_lib = "{worker_lib}"
logic_watch = "{worker_package}/src"
types_watch = "{types_package}/src"
# The host feature `flui run` turns on, with the host's default features off: it
# loads the worker library instead of linking the logic crate.
reload_feature = "{RELOAD_FEATURE}"
"#
    )
}

fn types_plan(types_package: &str, source: &DependencySource) -> ProjectPlan {
    let facade_dep = source.dependency(FrameworkPackage::Facade, &[]);
    let reload_dep = source.dependency(FrameworkPackage::HotReload, &["app-plugin"]);

    let cargo = format!(
        r#"[package]
name = "{types_package}"
version.workspace = true
edition.workspace = true
rust-version.workspace = true
publish = false
description = "Shared types and persistent State for the hot-reload app"

[dependencies]
flui = {facade_dep}
flui-hot-reload = {reload_dep}
"#
    );

    ProjectPlan::new()
        .file(format!("{types_package}/Cargo.toml"), cargo)
        .file(format!("{types_package}/src/lib.rs"), TYPES_LIB)
}

fn logic_plan(
    types_package: &str,
    worker_package: &str,
    worker_lib: &str,
    source: &DependencySource,
) -> ProjectPlan {
    let facade_dep = source.dependency(FrameworkPackage::Facade, &[]);
    let test_facade_dep = source.dependency(FrameworkPackage::Facade, &["testing"]);
    let reload_dep = source.dependency(FrameworkPackage::HotReload, &["app-plugin"]);
    let types_dep = member_dep(types_package);
    let types_crate = types_package.replace('-', "_");

    let cargo = format!(
        r#"[package]
name = "{worker_package}"
version.workspace = true
edition.workspace = true
rust-version.workspace = true
publish = false
description = "Reloadable UI logic (cdylib) — the hot-reload target"

[lib]
# `cdylib` is the library `flui run` reloads; `rlib` is what a release host links.
crate-type = ["cdylib", "rlib"]
name = "{worker_lib}"

[dependencies]
flui = {facade_dep}
flui-hot-reload = {reload_dep}
{types_package} = {types_dep}

[dev-dependencies]
flui = {test_facade_dep}
"#
    );

    let lib = LOGIC_LIB.replace("__TYPES_CRATE__", &types_crate);

    ProjectPlan::new()
        .file(format!("{worker_package}/Cargo.toml"), cargo)
        .file(format!("{worker_package}/src/lib.rs"), lib)
}

fn host_plan(
    name: &str,
    types_package: &str,
    host_package: &str,
    worker_package: &str,
    worker_lib: &str,
    source: &DependencySource,
) -> ProjectPlan {
    let facade_dep = source.dependency(FrameworkPackage::Facade, &[]);
    let reload_dep = source.dependency(FrameworkPackage::HotReload, &["app-plugin"]);
    let types_dep = member_dep(types_package);
    let worker_dep = optional_member_dep(worker_package);
    let types_crate = types_package.replace('-', "_");

    let cargo = format!(
        r#"[package]
name = "{host_package}"
version.workspace = true
edition.workspace = true
rust-version.workspace = true
publish = false
description = "Host binary — owns the element tree and loads the worker"

[[bin]]
name = "{host_package}"
path = "src/main.rs"

[features]
default = ["linked"]
# The logic crate linked into the host: `flui build` and `cargo build --release`
# load no library and install no reload hook.
linked = ["dep:{worker_package}"]
# What `flui run` builds instead (`reload_feature` in flui.toml, default features
# off): the host loads the logic crate's library and reloads it on each rebuild.
{RELOAD_FEATURE} = ["flui-hot-reload/host-hook"]

[dependencies]
flui = {facade_dep}
flui-hot-reload = {reload_dep}
{types_package} = {types_dep}
{worker_package} = {worker_dep}
tracing = {{ workspace = true }}
"#
    );

    let main = HOST_MAIN
        .replace("__NAME__", name)
        .replace("__HOST_PACKAGE__", host_package)
        .replace("__WORKER_PACKAGE__", worker_package)
        .replace("__WORKER_LIB__", worker_lib)
        .replace("__WORKER_CRATE__", worker_lib)
        .replace("__TYPES_CRATE__", &types_crate);

    ProjectPlan::new()
        .file(format!("{host_package}/Cargo.toml"), cargo)
        .file(format!("{host_package}/src/main.rs"), main)
}

