//! The application's `AndroidManifest.xml`, generated whole (ADR-0255
//! decision 6, ADR-0307).
//!
//! FLUI owns the base (`templates/android/AndroidManifest.xml`: the
//! Activity, its `configChanges`, the native library); the crates the
//! application links contribute what they declare
//! ([`Declarations`](crate::declarations::Declarations)); `flui.toml` gives the
//! label. Every build writes the file again at
//! `platforms/android/app/src/main/AndroidManifest.xml`, where both the
//! SDK-tools packager and Gradle read it, and only when it changed. A file
//! there that `flui build` did not write is refused rather than overwritten,
//! so a hand edit is never lost silently.

use std::path::{Path, PathBuf};

use crate::build::error::{BuildError, BuildResult};
use crate::build::util::xml::xml_escape;
use crate::declarations::Declarations;

/// FLUI's base manifest, with `{{app_name}}`, `{{lib_name}}` and
/// `{{uses_permissions}}` to fill.
const BASE: &str = include_str!("../../templates/android/AndroidManifest.xml");

/// What the base's header says, by which a file `flui build` wrote is told
/// from one it did not.
const GENERATED: &str = "Generated by `flui build`";

/// Whether `manifest` is a file `flui build` wrote, by its header.
#[must_use]
pub(crate) fn is_generated(manifest: &str) -> bool {
    manifest.contains(GENERATED)
}

/// Where a project's manifest lives, under `project`: both packagers read it
/// there.
#[must_use]
pub(crate) fn path_in(project: &Path) -> PathBuf {
    project
        .join("platforms")
        .join("android")
        .join("app")
        .join("src")
        .join("main")
        .join("AndroidManifest.xml")
}

/// What the application gives its manifest.
#[derive(Debug, Clone, Copy)]
pub(crate) struct ManifestFacts<'a> {
    /// The label the launcher shows: `flui.toml`'s `[app] name`.
    pub(crate) label: &'a str,
    /// The native library `NativeActivity` loads, without `lib` and `.so`.
    pub(crate) lib_name: &'a str,
}

/// The manifest for `facts` and what the linked crates declare.
#[must_use]
pub(crate) fn render(facts: &ManifestFacts<'_>, declarations: &Declarations) -> String {
    let mut uses_permissions = String::new();
    for (permission, _) in declarations.android_permissions() {
        uses_permissions.push_str("    <uses-permission android:name=\"");
        uses_permissions.push_str(permission.as_str());
        uses_permissions.push_str("\" />\n");
    }
    BASE.replace("{{uses_permissions}}\n", &uses_permissions)
        .replace("{{app_name}}", &xml_escape(facts.label))
        .replace("{{lib_name}}", &xml_escape(facts.lib_name))
}

/// Writes [`render`]'s manifest to `path` unless it already holds it.
///
/// # Errors
///
/// [`BuildError::InvalidConfig`] when `path` holds a manifest `flui build`
/// did not write, and the failure to read or write it.
pub(crate) fn write(
    path: &Path,
    facts: &ManifestFacts<'_>,
    declarations: &Declarations,
) -> BuildResult<()> {
    let manifest = render(facts, declarations);
    match std::fs::read_to_string(path) {
        Ok(existing) if existing == manifest => return Ok(()),
        Ok(existing) if !is_generated(&existing) => {
            return Err(BuildError::invalid_config(
                path.display().to_string(),
                "is not the manifest `flui build` generates. FLUI writes it on every build from \
                 flui.toml and the `[package.metadata.flui.declares]` of the crates the app \
                 links (ADR-0307); move any change you made there, delete the file, and build \
                 again",
            ));
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)?;
            }
        }
        Err(error) => return Err(error.into()),
    }
    for (permission, crates) in declarations.android_permissions() {
        crate::ui::debug(format!(
            "AndroidManifest.xml: {permission}, declared by {}",
            crates.iter().cloned().collect::<Vec<_>>().join(", ")
        ));
    }
    std::fs::write(path, manifest)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::{ManifestFacts, render, write};
    use crate::declarations::Declarations;

    const FACTS: ManifestFacts<'static> = ManifestFacts {
        label: "R&D <Notes>",
        lib_name: "notes",
    };

    /// The declarations of FLUI's own workspace, built for Android with the
    /// features an application gets by default.
    fn framework_declarations() -> Declarations {
        let workspace = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        Declarations::collect(&workspace, &["aarch64-linux-android"])
            .expect("the workspace's declarations")
    }

    /// The manifest declares each permission the framework's Android host
    /// needs, because the crate that needs it declares it: `flui-native`'s
    /// haptic patterns the vibrator, `flui-app`'s `http` feature (on by
    /// default) the network for `HttpURLConnection`. The label and library
    /// are escaped into the base, which keeps its Activity.
    #[test]
    fn the_manifest_declares_what_the_linked_crates_need() {
        let manifest = render(&FACTS, &framework_declarations());
        for line in [
            "    <uses-permission android:name=\"android.permission.INTERNET\" />\n",
            "    <uses-permission android:name=\"android.permission.VIBRATE\" />\n",
            "android:label=\"R&amp;D &lt;Notes&gt;\"",
            "android:value=\"notes\"",
            "android:name=\"android.app.NativeActivity\"",
        ] {
            assert!(manifest.contains(line), "{line:?} in\n{manifest}");
        }
        assert!(
            !manifest.contains("{{"),
            "every placeholder filled:\n{manifest}"
        );
        let without = render(&FACTS, &Declarations::default());
        assert!(!without.contains("<uses-permission"), "{without}");
    }

    /// The file is written when missing or stale, left alone when current,
    /// and a manifest `flui build` did not write is refused untouched.
    #[test]
    fn the_manifest_is_rewritten_only_when_flui_wrote_it() {
        let dir = tempfile::tempdir().expect("a temporary directory");
        let path = dir.path().join("app/src/main/AndroidManifest.xml");
        let declarations = Declarations::default();

        write(&path, &FACTS, &declarations).expect("a first write");
        assert_eq!(
            std::fs::read_to_string(&path).expect("the manifest"),
            render(&FACTS, &declarations)
        );

        let renamed = ManifestFacts {
            label: "Notes",
            ..FACTS
        };
        write(&path, &renamed, &declarations).expect("a stale manifest rewritten");
        assert!(
            std::fs::read_to_string(&path)
                .expect("the manifest")
                .contains("android:label=\"Notes\"")
        );

        let hand_written = "<manifest><uses-permission android:name=\"a.B\" /></manifest>\n";
        std::fs::write(&path, hand_written).expect("a hand-written manifest");
        let refused = write(&path, &FACTS, &declarations).expect_err("a hand-written manifest");
        assert!(refused.to_string().contains("delete the file"), "{refused}");
        assert_eq!(
            std::fs::read_to_string(&path).expect("the manifest"),
            hand_written
        );
    }
}
